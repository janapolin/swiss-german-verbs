"""Tests for the rendering engine — the linguistic core (§6).

Fixture data is hand-copied from `data/verbs_irregular.csv` and
`data/verbs_regular.csv`, reshaped into the *bare*, ingestion-normalised form
the domain layer actually sees (§5): separable verbs store forms with the
prefix stripped — e.g. uufhänke's CSV participle `uufghänkt` becomes the bare
`ghänkt` plus `separable_prefix="uuf"`. Regular verbs' present forms are
generated by `expand_regular` at ingestion time (§13, out of scope for this
milestone), so they're spelled out here by hand following the class-A rule
(stem + `-e/-sch/-t/-ed`, grammar_rules.md §1): `mache` -> stem `mach`,
`uufhänke` -> strip prefix, stem `hänk`.

`ha.present_sg3` is taken verbatim from the seed CSV (`het` — the owner resolved
the §17 "hät vs het" open item by storing the "common variant" `het`); this
suite locks in whatever the seed currently says.
"""

