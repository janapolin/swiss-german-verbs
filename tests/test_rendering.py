# --- §6: "a regular class-A verb: mache (ha, non-separable) in all four tenses"


def test_mache_present():
    assert render(MACHE, MACHE_FORMS, Tense.PRESENT, Person.SG3, AUX) == "er macht"


def test_mache_perfect():
    assert render(MACHE, MACHE_FORMS, Tense.PERFECT, Person.SG3, AUX) == "er het gmacht"


def test_mache_future():
    assert render(MACHE, MACHE_FORMS, Tense.FUTURE, Person.SG3, AUX) == "er wird mache"


def test_mache_konjunktiv2_slot_does_not_exist():
    # mache isn't one of the six KII verbs (grammar_rules.md §6) -> the konj2
    # slot doesn't exist; card_gen must not emit it, and render must refuse (§6).
    assert MACHE.has_konjunktiv2 is False
    with pytest.raises(ValueError):
        render(MACHE, MACHE_FORMS, Tense.KONJ2, Person.SG3, AUX)


# --- §6: "a separable verb: uufhänke (ha, prefix uuf) — present, perfect, future"


def test_uufhaenke_present_detaches_prefix_to_clause_end():
    assert render(UUFHAENKE, UUFHAENKE_FORMS, Tense.PRESENT, Person.SG3, AUX) == "er hänkt uuf"


def test_uufhaenke_perfect_reattaches_prefix_to_participle():
    assert render(UUFHAENKE, UUFHAENKE_FORMS, Tense.PERFECT, Person.SG3, AUX) == "er het uufghänkt"


def test_uufhaenke_future_keeps_infinitive_attached():
    assert render(UUFHAENKE, UUFHAENKE_FORMS, Tense.FUTURE, Person.SG3, AUX) == "er wird uufhänke"


# --- §6: "perfect with si: choo (si) — er isch choo" -------------------------


def test_choo_perfect_uses_si_auxiliary():
    assert render(CHOO, CHOO_FORMS, Tense.PERFECT, Person.SG3, AUX) == "er isch choo"


# --- §6: "KII: ha -> er hätt, si -> er wär, wele -> er wett" -----------------


