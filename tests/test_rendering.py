# --- §6: "future of werde itself (edge case): er wird werde" ----------------


def test_werde_future_of_itself():
    assert render(WERDE, WERDE_FORMS, Tense.FUTURE, Person.SG3, AUX) == "er wird werde"


# --- §6: override hook — a pre-assembled string bypasses rule-based assembly -


def test_override_hook_bypasses_assembly_for_that_cell_only():
    overridden = VerbForms(
        verb_id=141,
        present_sg1="hänke",
        present_sg2="hänksch",
        present_sg3="hänkt",
        present_pl="hänked",
        participle="ghänkt",
        overrides={(Tense.PRESENT, Person.SG3): "er hänkt grad uuf"},
    )

    assert render(UUFHAENKE, overridden, Tense.PRESENT, Person.SG3, AUX) == "er hänkt grad uuf"
    # Cells without an override still fall through to rule-based assembly.
    assert render(UUFHAENKE, overridden, Tense.FUTURE, Person.SG3, AUX) == "er wird uufhänke"


# --- pronouns/persons beyond sg3, spot-checked across all four tenses --------


@pytest.mark.parametrize(
    ("person", "expected"),
    [
        (Person.SG1, "ich mache"),
        (Person.SG2, "du machsch"),
        (Person.SG3, "er macht"),
        (Person.PL, "mir mached"),
    ],
)
def test_present_renders_every_person(person: Person, expected: str):
    assert render(MACHE, MACHE_FORMS, Tense.PRESENT, person, AUX) == expected
